-- Run in Supabase SQL Editor. Existing planner_data table is not modified.
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null,
  subscription jsonb not null,
  timezone text not null default 'UTC',
  updated_at timestamptz not null default now(),
  unique (user_id, endpoint)
);
alter table public.push_subscriptions add column if not exists timezone text not null default 'UTC';
alter table public.push_subscriptions enable row level security;
drop policy if exists "Users manage their own push subscriptions" on public.push_subscriptions;
create policy "Users manage their own push subscriptions"
  on public.push_subscriptions for all to authenticated
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- `sent_reminders` from older versions is no longer used. Delivery is tracked per subscription below.

-- Enable these extensions if they are not already enabled, then follow PUSH_SETUP_FA.md
-- to create a Supabase Cron job that invokes the send-reminders Edge Function every minute.

-- Delivery is tracked per task AND per browser subscription. This prevents a successful
-- delivery to one device from suppressing delivery to another device on the same account.
create table if not exists public.push_delivery_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription_id bigint not null references public.push_subscriptions(id) on delete cascade,
  task_id text not null,
  task_date date not null,
  sent_at timestamptz not null default now(),
  unique (user_id, subscription_id, task_id, task_date)
);
alter table public.push_delivery_log enable row level security;
-- Intentionally no client-facing policies. Only the Edge Function service role accesses this table.
